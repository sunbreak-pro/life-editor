/*
 * Dump the MCP tool registry to a JSON catalog the app can display (#1210).
 *
 * Settings' AI card lists what Claude Code can actually do to this database.
 * The names and descriptions for that list already exist — in `TOOLS`
 * (src/tools.ts) — but shared/ cannot import them: each `tools/<domain>.ts`
 * pulls its handlers in, and the handlers pull in the Supabase client, so a
 * direct import would drag the server's whole data layer into the browser
 * bundle. The catalog crosses the package line as DATA instead, generated
 * here and committed under shared/src/generated/.
 *
 * Reads dist/, not src/: this is plain Node with no TypeScript loader, so the
 * package has to be built first (`npm run catalog` chains the two). Importing
 * the registry runs no queries — `getSupabase()` is lazy, and nothing here
 * calls a handler.
 *
 * The file is generated by hand, not by `npm run build`, so tools/catalog can
 * drift. mcp-server/tests/toolCatalogFreshness.test.ts is what closes that:
 * it compares the committed catalog against the live registry and fails when
 * a tool was added without re-running this script.
 */

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));

let TOOLS;
try {
  ({ TOOLS } = await import("../dist/tools.js"));
} catch (e) {
  console.error(
    "[dump-tool-catalog] cannot read dist/tools.js — build first:\n" +
      "  cd mcp-server && npm run build\n",
    e,
  );
  process.exit(1);
}

const catalog = TOOLS.map(({ name, description, inputSchema }) => ({
  name,
  description,
  inputSchema,
}));

const out = resolve(here, "../../shared/src/generated/mcpToolCatalog.json");
// Trailing newline + 2-space indent: the repo's Prettier settings for JSON,
// so a regenerated catalog does not come back as a whitespace diff.
writeFileSync(out, `${JSON.stringify(catalog, null, 2)}\n`, "utf8");
console.log(`[dump-tool-catalog] wrote ${catalog.length} tools -> ${out}`);
